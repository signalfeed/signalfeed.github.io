"""Minnesota Title II PDF readiness pages, rendered by build.py from src/mn-readiness.json
(generated by tools/readiness/summarize.py in the SignalFeed tools repo)."""
import json
from html import escape as e
from pathlib import Path
from urllib.parse import quote

INDEX = "mn-title-ii-pdf-readiness.html"
DL = {"2027-04-26": "April 26, 2027", "2028-04-26": "April 26, 2028"}
FIX = {
    "untagged": ("Most PDFs we sampled have no tag structure.",
                 "The quickest win is at the source: in Word, use real Heading styles and save with File > Save As > PDF > Options > "
                 "“Document structure tags for accessibility” turned on. New agendas and notices then publish tagged instead of adding to the backlog."),
    "scanned": ("A large share of the PDFs we sampled are scanned images with no selectable text.",
                "Scanned pages need OCR before anything else, and then tags. Where the original Word or Excel file still exists, exporting a fresh tagged PDF from it is usually cheaper than fixing the scan."),
    "lang": ("Many PDFs we sampled have no document language set.",
             "Setting the language (for example en-US) lets screen readers pronounce text correctly. In Word it follows the proofing language; in Acrobat it is under File > Properties > Advanced > Language."),
    "title": ("Many PDFs we sampled have no document title.",
              "Fill in File > Properties > Title in Word before exporting, so the title rather than a file name is announced."),
    "verify": ("Most PDFs we sampled pass the basic checks.",
               "The next step is the part automation cannot do: check reading order, table headers and image descriptions in a sample of the most-used documents."),
}


OFFER = ("If this is useful, send us one public document from your site (an agenda, minutes, a budget or a report, not a completed form or anything holding "
         "personal information) and we will return 2 pages rebuilt as a tagged PDF with a veraPDF report, free. A person reviews every sample by hand before it goes back. "
         "Larger jobs are quoted only after we have reviewed the actual files, because scanned pages, complex tables and forms are priced separately.")


def pct(v):
    return "n/a" if v is None else f"{v:g}%"


def num(v):
    return f"{v:,}" if isinstance(v, int) else e(str(v))


METHOD = """<h2 id="method">Method and limits</h2>
<p>These are <strong>automated checks, not a legal finding</strong> and not a WCAG conformance test. In November 2026 a crawler identifying itself as SignalFeedReadinessBot visited up to 300 public HTML pages on each city&#39;s main website, obeying robots.txt and making at most one request per second. It collected PDF links on the same website and analyzed up to 400 of them (a random sample where more were found). It did not log in, submit forms, or get around any bot protection; a site that blocked or challenged it is reported as blocked.</p>
<p>For each PDF it recorded the page count, whether the file has a tag structure (a StructTreeRoot), whether a document language and title are set, and whether sampled pages have extractable text (pages that are images only are counted as scanned). Up to 20 PDFs per city were also run through <a href="https://verapdf.org/">veraPDF</a> against PDF/UA-1, the machine-checkable part of PDF accessibility.</p>
<ul>
<li><strong>Passing these checks does not make a PDF accessible.</strong> Reading order, correct tags, table headers and image descriptions need a person.</li>
<li><strong>Not every PDF must be fixed.</strong> The rule (28 CFR 35.201) has exceptions, including archived content kept only for reference and some preexisting documents. We cannot tell from the outside which files qualify.</li>
<li>Coverage is partial: 300 pages is not the whole site, and documents in agenda systems, third-party portals or other domains were not counted.</li>
<li>&ldquo;Estimated pages to remediate&rdquo; adds up the pages of sampled PDFs that fail at least one basic check (no tags, no language, or scanned) and scales that to all PDF links found. Treat it as an order of magnitude.</li>
</ul>"""


def stats(c):
    rows = [
        ("Title II compliance date", DL.get(c["deadline"], c["deadline"])),
        ("Population (2020 Census)", num(c["population"])),
        ("Site pages crawled", num(c["pages_crawled"])),
        ("PDF links found on those pages", num(c["pdf_links_found"])),
        ("PDFs analyzed", num(c["pdfs_analyzed"])),
        ("Tagged (have a structure tree)", pct(c["pct_tagged"])),
        ("Document language set", pct(c["pct_lang"])),
        ("Document title set", pct(c["pct_title"])),
        ("Scanned (image-only pages)", pct(c["pct_scanned"])),
        ("Changed in 2024 or later (PDF date)", pct(c["pct_modified_2024_plus"])),
        ("Passed veraPDF PDF/UA-1", f'{c["vera_passed"]} of {c["vera_tested"]} tested'),
        ("Estimated pages to remediate", num(c["est_pages_to_remediate"])),
    ]
    body = "".join(f"<tr><th scope=\"row\">{e(k)}</th><td>{v}</td></tr>" for k, v in rows)
    return (f'<div class="table-scroll" role="region" aria-label="{e(c["city"])} results" tabindex="0"><table>'
            f'<caption>{e(c["city"])}: automated PDF checks, crawled {e(c["crawled_at"])}</caption>'
            f'<thead><tr><th scope="col">Measure</th><th scope="col">Result</th></tr></thead><tbody>{body}</tbody></table></div>')


def city_page(c, email):
    name = c["city"]
    subj = quote(f"Correction or removal: {name} readiness page")
    quote_subj = quote(f"Free 2-page sample: {name}")
    if not c["pdfs_analyzed"] and c.get("robots_skipped"):
        core = (f'<p>{e(name)} must make its web content, including posted PDFs, meet WCAG 2.1 Level AA by '
                f'<strong>{DL.get(c["deadline"], c["deadline"])}</strong> under the ADA Title II web rule.</p>'
                f'<p>Our crawler found <strong>{num(c["pdf_links_found"])} PDF links</strong> on {num(c["pages_crawled"])} pages of {e(c["start_url"])}, '
                f'but the site&#39;s robots.txt asks crawlers not to fetch the folder those PDFs are stored in, so we did not download or check them. '
                "No PDF results are reported.</p>"
                "<h2>What stands out</h2><p>The same robots.txt rule also asks search engines to skip those documents, so residents may not find them through search. "
                "If that is not intended, it is a one-line change to robots.txt. If you would like these files checked, send us a few and we will report on them privately.</p>")
    elif c["status"] == "blocked" or not c["pdfs_analyzed"]:
        core = (f"<p>Our crawler could not analyze PDFs on {e(name)}&#39;s website "
                f"({'the site blocked or challenged automated requests' if c['status'] == 'blocked' else 'no same-site PDFs were reachable'}). "
                "We did not try to get around that. No results are reported.</p>")
    else:
        lead, fix = FIX[c["main_issue"]]
        ex = "".join(
            f'<li><a href="{e(x["url"])}">{e(x["title"] or x["url"].rsplit("/", 1)[-1] or "Document")}</a>: {x["pages"]} pages; '
            f'{"tagged" if x["tagged"] else "no tags"}; {"language " + e(x["lang"]) if x["lang"] else "no language"}'
            f'{"; scanned" if x["scanned"] else ""}</li>' for x in c["examples"][:6])
        core = (f'<p>{e(name)} must make its web content, including posted PDFs, meet WCAG 2.1 Level AA by '
                f'<strong>{DL.get(c["deadline"], c["deadline"])}</strong> under the ADA Title II web rule. '
                f'Here is what an automated scan of {e(c["start_url"])} found.</p>'
                + stats(c)
                + f'<h2>What stands out</h2><p>{e(lead)} {e(fix)}</p>'
                + (f'<p>{num(c["robots_skipped"])} of the PDF links we found sit in a folder that the site&#39;s robots.txt asks crawlers not to fetch, '
                   'so we did not check them and they are not in these numbers.</p>' if c.get("robots_skipped") else "")
                + (f'<h2>Largest documents failing a basic check</h2><p>These are examples, not a complete list.</p><ul>{ex}</ul>' if ex else ""))
    body = (core
            + f'<h2>Free sample</h2><p>{OFFER}</p>'
              f'<p><a class="btn btn-primary" href="mailto:{email}?subject={quote_subj}">Request a free 2-page sample</a></p>'
            + METHOD
            + f'<h2>Corrections</h2><p>If a number here is wrong, a document is exempt or already replaced, or you would like this page taken down, '
              f'<a href="mailto:{email}?subject={subj}">email {email}</a> and we will correct or remove it.</p>'
            + f'<p><a href="{INDEX}">All 20 Minnesota cities</a></p>')
    return {"slug": f"mn-readiness-{c['slug']}.html", "kind": "Data", "og": "title-ii-pdf-guide",
            "title": f"{name}, MN: Title II PDF Readiness | SignalFeed.dev",
            "description": f"Automated ADA Title II PDF check of the City of {name}, Minnesota website: tagging, language, scanned files and veraPDF results, with method and limits.",
            "h1": f"Title II PDF readiness: {e(name)}, Minnesota", "body": body}


def index_page(rows, email):
    ok = [c for c in rows if c["pdfs_analyzed"]]
    tot = sum(c["pdfs_analyzed"] for c in ok)
    w = lambda k: round(sum((c[k] or 0) * c["pdfs_analyzed"] for c in ok) / tot, 1) if tot else 0
    vt, vp = sum(c["vera_tested"] for c in ok), sum(c["vera_passed"] for c in ok)
    trs = "".join(
        f'<tr><th scope="row"><a href="mn-readiness-{c["slug"]}.html">{e(c["city"])}</a></th><td>{num(c["population"])}</td>'
        f'<td>{DL.get(c["deadline"], "")}</td><td>{num(c["pdfs_analyzed"]) if c["pdfs_analyzed"] else ("not crawled (robots.txt)" if c.get("robots_skipped") else e(c["status"]))}</td>'
        f'<td>{pct(c["pct_tagged"])}</td><td>{pct(c["pct_lang"])}</td><td>{pct(c["pct_scanned"])}</td>'
        f'<td>{num(c["est_pages_to_remediate"])}</td></tr>' for c in rows)
    body = (f'<p>The ADA Title II web rule requires cities to make web content, including posted PDFs, meet WCAG 2.1 Level AA by '
            f'<strong>April 26, 2027</strong> (population 50,000 or more) or <strong>April 26, 2028</strong> (smaller). '
            f'In November 2026 we ran the same automated PDF checks on the websites of {len(rows)} Minnesota cities: '
            f'{sum(c["population"] >= 50000 for c in rows)} larger and {sum(c["population"] < 50000 for c in rows)} smaller.</p>'
            f'<h2>Across all {len(rows)} cities</h2><ul><li>{tot:,} PDFs analyzed</li><li>{w("pct_tagged")}% tagged</li>'
            f'<li>{w("pct_lang")}% with a document language set</li><li>{w("pct_scanned")}% scanned</li>'
            f'<li>{vp} of {vt} sampled PDFs passed veraPDF PDF/UA-1</li>'
            f'<li>About {sum(c["est_pages_to_remediate"] for c in ok):,} pages estimated to need work</li></ul>'
            f'<div class="table-scroll" role="region" aria-label="Results by city" tabindex="0"><table><caption>Automated PDF checks by city (select a city for details)</caption>'
            f'<thead><tr><th scope="col">City</th><th scope="col">Population</th><th scope="col">Deadline</th><th scope="col">PDFs analyzed</th>'
            f'<th scope="col">Tagged</th><th scope="col">Language set</th><th scope="col">Scanned</th><th scope="col">Est. pages to remediate</th></tr></thead>'
            f'<tbody>{trs}</tbody></table></div>'
            f'<h2>Free sample</h2><p>{OFFER}</p>'
            f'<p><a class="btn btn-primary" href="mailto:{email}?subject={quote("Free 2-page sample")}">Request a free 2-page sample</a></p>'
            + METHOD
            + f'<h2>Corrections</h2><p>City staff can ask for a correction or removal at <a href="mailto:{email}?subject={quote("Correction or removal: MN readiness")}">{email}</a>.</p>')
    return {"slug": INDEX, "kind": "Data", "og": "title-ii-pdf-guide",
            "title": "Minnesota Title II PDF Readiness: 20 Cities | SignalFeed.dev",
            "description": "Automated ADA Title II PDF checks of 20 Minnesota city websites: how many PDFs are tagged, have a language set or are scanned, with method and limits.",
            "h1": "Minnesota Title II PDF readiness", "body": body}


def pages(path, email):
    p = Path(path)
    if not p.exists():
        return []
    rows = json.loads(p.read_text())
    return [index_page(rows, email)] + [city_page(c, email) for c in rows]
